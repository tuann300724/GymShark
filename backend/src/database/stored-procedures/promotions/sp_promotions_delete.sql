CREATE OR ALTER PROCEDURE [dbo].[sp_promotions_delete]
  @id UNIQUEIDENTIFIER
AS BEGIN
  SET NOCOUNT ON;
  BEGIN TRY
    BEGIN TRANSACTION;
    DELETE FROM dbo.promotions WHERE id = @id;
    COMMIT TRANSACTION;
  END TRY
  BEGIN CATCH
    IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
    DECLARE @E NVARCHAR(4000) = ERROR_MESSAGE();
    DECLARE @S INT = ERROR_SEVERITY(); DECLARE @St INT = ERROR_STATE();
    RAISERROR(@E, @S, @St);
  END CATCH
END
