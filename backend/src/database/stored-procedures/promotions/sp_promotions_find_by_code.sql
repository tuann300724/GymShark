CREATE OR ALTER PROCEDURE [dbo].[sp_promotions_find_by_code]
  @code VARCHAR(50)
AS BEGIN
  SET NOCOUNT ON;
  BEGIN TRY
    SELECT * FROM dbo.promotions WHERE code = @code;
  END TRY
  BEGIN CATCH DECLARE @E NVARCHAR(4000)=ERROR_MESSAGE(); DECLARE @S INT=ERROR_SEVERITY(); DECLARE @St INT=ERROR_STATE(); RAISERROR(@E,@S,@St); END CATCH
END
