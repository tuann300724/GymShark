CREATE OR ALTER PROCEDURE [dbo].[sp_promotions_set_status]
  @id UNIQUEIDENTIFIER,
  @status VARCHAR(20)
AS BEGIN
  SET NOCOUNT ON;
  BEGIN TRY
    BEGIN TRANSACTION;
    UPDATE dbo.promotions SET status = @status, updatedAt = GETDATE() WHERE id = @id;
    COMMIT TRANSACTION;
  END TRY
  BEGIN CATCH
    IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
    DECLARE @E NVARCHAR(4000) = ERROR_MESSAGE();
    DECLARE @S INT = ERROR_SEVERITY(); DECLARE @St INT = ERROR_STATE();
    RAISERROR(@E, @S, @St);
  END CATCH
END
