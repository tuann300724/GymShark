CREATE OR ALTER PROCEDURE [dbo].[sp_notifications_delete]
  @id UNIQUEIDENTIFIER
AS BEGIN
  SET NOCOUNT ON;
  BEGIN TRY
    DELETE FROM dbo.notifications WHERE id = @id;
  END TRY
  BEGIN CATCH DECLARE @E NVARCHAR(4000)=ERROR_MESSAGE(); DECLARE @S INT=ERROR_SEVERITY(); DECLARE @St INT=ERROR_STATE(); RAISERROR(@E,@S,@St); END CATCH
END
